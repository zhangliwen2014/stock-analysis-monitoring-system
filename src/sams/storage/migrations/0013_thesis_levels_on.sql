-- 0013：`theses.levels_on`——库里那几列价位是按哪一天的读数算出来的（spec D79 的续）
--
-- `show` 那屏并排给了「库里那次」与「当前这次」，而它只能靠 `created_at`（落库的一刻）
-- 说库里那次属于什么时候。这两件事不是一回事：立论时传 `--as-of 2024-07-11`，
-- 那四个价位是**那一天**的测量，而 `created_at` 是今天写库的那一秒。拿写入时刻当测量日，
-- 一屏就会把「按 7 月 11 日的库定的计划」读成「今天重新量过一遍，没变」——
-- 而两栏相等在这里恰恰是必然的：当前那次也是按今天重算的，两者根本不是同一把尺。
--
-- 于是「漂移」在这里读不出来（快照还没有写入方，D76/D79）。这一列至少能让屏幕说对一件事：
-- 库里那几列**属于哪一天**。手填的那几个数没有测量日，留 NULL 而不是填今天——
-- 「我今天填的止损」与「今天的行情算出的止损」在回看时是两个结论。
ALTER TABLE theses ADD COLUMN IF NOT EXISTS levels_on DATE;
