-- 0017：`rules.params_on`——那一屏参数属于哪一天的价空间（spec §10.2 的除权换算）
--
-- 「除权日不许误报跌破止损」要靠把人写下来的价搬进今天的坐标系，而搬需要一个锚：那个数
-- 是哪一天填的。库里现成的两列都不是它。`created_at` 是这一行第一次落库的一刻，之后
-- `params_json` 还能被整份换掉；`updated_at` 更糟——`set_enabled` 每启停一次就碰它一次，
-- 于是去年填的那条线被停用再启用一次，就获得了「今天填的」这个身份，而「今天填的」在
-- 换算里等于免搬：恰好把误报的方向搞反。
--
-- 所以单独一列，只在参数真的被改过时盖章（`RuleRepo.update` 里那一句）。
-- 旧行留 NULL：「不知道哪天填的」不是「今天填的」，读取侧因此不许拿它做判断，
-- 只能报一句说得出下一步的 skipped（0013 给 `levels_on` 留空是同一个理由）。
-- 可空也是 DuckDB 的限制：`ADD COLUMN` 不能带 NOT NULL（0015/0016 的头注是同一条）。
ALTER TABLE rules ADD COLUMN IF NOT EXISTS params_on DATE;
